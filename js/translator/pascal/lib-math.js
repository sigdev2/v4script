    function mathNatives(rt) {
        var check = function (argument, result) {
            if (result !== result && argument === argument)
                rt.re(207);
            return result;
        };
        return {
            methods: {},
            routines: {
                // The mask of floating-point exceptions (bits by TFPUException):
                // a masked one gives NaN or an infinity instead of an error.
                fpumaskbits: function (bits, change) {
                    var old = rt.fpuMask;
                    if (change)
                        rt.fpuMask = bits & 63;
                    return old;
                },
                isnan: function (value) { return value !== value; },
                isinfinite: function (value) { return value === Infinity || value === -Infinity; },
                tan: function (value) { return Math.tan(value); },
                arccos: function (value) { return check(value, Math.acos(value)); },
                arcsin: function (value) { return check(value, Math.asin(value)); },
                cosh: function (value) { return Math.cosh(value); },
                sinh: function (value) { return Math.sinh(value); },
                tanh: function (value) { return Math.tanh(value); },
                arccosh: function (value) { return check(value, Math.acosh(value)); },
                arcsinh: function (value) { return Math.asinh(value); },
                arctanh: function (value) { return check(value, Math.atanh(value)); },
                arcosh: function (value) { return check(value, Math.acosh(value)); },
                arsinh: function (value) { return Math.asinh(value); },
                artanh: function (value) { return check(value, Math.atanh(value)); }
            }
        };
    }

